const BRAND_WORDS = new Set([
  "metretag", "metrepoint", "metre app", "metre console", "metre", "uwb", "app", "console",
  "tag", "point", "device", "products",
]);

export function matchFaq(text) {
  const t = String(text || "").trim();
  if (!t) return null;

  // Exact slash-command match (strip a trailing @botname).
  if (t.startsWith("/")) {
    const cmd = t.split(/\s+/)[0].toLowerCase().replace(/@.*$/, "");
    const entry = faqEntries.find((e) => (e.commands || []).includes(cmd));
    return entry ? { entry, lang: "zh", command: cmd } : null;
  }

  // Keyword match for common questions.
  const lower = t.toLowerCase();
  let best = null;
  let bestScore = 0;
  for (const entry of faqEntries) {
    let score = 0;
    for (const kw of entry.keywords || []) {
      if (lower.includes(kw.toLowerCase())) {
        const k = kw.toLowerCase();
        if (BRAND_WORDS.has(k) || k.includes("metre")) {
          score += 1; // generic brand term
        } else {
          score += 10; // specific intent term
        }
      }
    }
    if (score > bestScore) {
      bestScore = score;
      best = entry;
    }
  }
  if (best && bestScore >= 10) {
    return { entry: best, lang: detectLanguage(t), command: null };
  }
  return null;
}

export function faqReply(match, sessionLang) {
  if (!match) return null;
  const lang = sessionLang || match.lang || "zh";
  let body;
  if (lang === "en") body = match.entry.en;
  else if (lang === "zh-Hans") body = zhHansData[match.entry.id] || match.entry.zh;
  else body = match.entry.zh;
  return { reply: body, id: match.entry.id, title: match.entry.id };
}
